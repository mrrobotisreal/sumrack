import { DEVICE_LOCAL_SETTING_KEYS, SYNCED_TABLES, type TableSpec } from './registry';

/**
 * Emits the outbox-trigger block of migration 0023_sync from the registry
 * (T104 F). `scripts/gen-sync-triggers.ts` splices it between the markers;
 * `__tests__/triggers.test.ts` regenerates and diffs, so the SQL and the
 * registry cannot drift. Pure string building — no native imports.
 */
export const TRIGGER_BEGIN = '-- >>> sync triggers (generated by scripts/gen-sync-triggers.ts; do not edit)';
export const TRIGGER_END = '-- <<< sync triggers';

const MS_NOW = "CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)";
const ACTIVE = '(SELECT applying FROM sync_control) = 0';

function pkExpr(t: TableSpec, row: 'NEW' | 'OLD'): string {
  return `json_array(${t.pk.map((c) => `${row}.\`${c}\``).join(', ')})`;
}

function settingsGuard(row: 'NEW' | 'OLD'): string {
  const keys = [...DEVICE_LOCAL_SETTING_KEYS]
    .sort()
    .map((k) => `'${k}'`)
    .join(', ');
  return ` AND ${row}.\`key\` NOT IN (${keys}) AND ${row}.\`key\` NOT LIKE 'sync.%' AND ${row}.\`key\` NOT LIKE 'auth.%'`;
}

function body(t: TableSpec, op: 'upsert' | 'delete', row: 'NEW' | 'OLD'): string {
  return (
    `UPDATE sync_clock SET last = MAX(last + 1, ${MS_NOW});\n` +
    `  INSERT INTO sync_outbox (tbl, pk, op, hlc, created_at) VALUES ('${t.name}', ${pkExpr(t, row)}, '${op}', (SELECT last FROM sync_clock), ${MS_NOW});`
  );
}

function trigger(t: TableSpec, event: 'INSERT' | 'UPDATE' | 'DELETE'): string {
  const row = event === 'DELETE' ? 'OLD' : 'NEW';
  const op = event === 'DELETE' ? 'delete' : 'upsert';
  const guard = t.cls === 'settings' ? settingsGuard(row) : '';
  return (
    `CREATE TRIGGER \`sync_${t.name}_${event.toLowerCase()}\` AFTER ${event} ON \`${t.name}\`\n` +
    `WHEN ${ACTIVE}${guard}\n` +
    `BEGIN\n  ${body(t, op, row)}\nEND;`
  );
}

export function generateTriggerSql(): string {
  const parts: string[] = [];
  for (const t of SYNCED_TABLES) {
    parts.push(trigger(t, 'INSERT'));
    if (t.insertOnly) continue;
    parts.push(trigger(t, 'UPDATE'));
    parts.push(trigger(t, 'DELETE'));
  }
  return `${TRIGGER_BEGIN}\n${parts.join('--> statement-breakpoint\n')}\n${TRIGGER_END}`;
}

/** Replace the marked block (or append it) in a migration file's text. */
export function spliceTriggerBlock(migration: string): string {
  const block = generateTriggerSql();
  const i = migration.indexOf(TRIGGER_BEGIN);
  if (i < 0) return `${migration.trimEnd()}\n--> statement-breakpoint\n${block}\n`;
  const j = migration.indexOf(TRIGGER_END, i);
  return migration.slice(0, i) + block + migration.slice(j + TRIGGER_END.length);
}
